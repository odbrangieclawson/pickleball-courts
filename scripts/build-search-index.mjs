/*
  BUILD THE SEARCH INDEX, ONCE, AT BUILD TIME.

      npm run build:search-index      (runs inside prebuild)

  /search/ is the only route this site renders on demand. Every other page
  is prerendered, so every other page pays the cost of the data layer at
  build time and none at request time. Search used to pay it per cold
  start: data.csv is 18,038 rows and 7.5 MB, the verified overlay and
  promotion run over all of it, the link graph is rebuilt, and a 6.8 MB
  Census ZCTA file is parsed for ZIP lookups. Roughly 14 MB of text and the
  whole data layer, to answer one query about 385 published pages — and the
  same work needs --max-old-space-size=2048 when the build does it.

  This writes data/search-index.json instead: the published entries, the
  ZIP codes that resolve to a county we publish, and the site's venue
  total. The function reads that and touches nothing else.

  The file is committed. It is derived, so it must be rebuilt whenever the
  published set changes — which is why this runs in prebuild rather than
  being a thing somebody remembers.
*/
import {writeFileSync, mkdirSync} from 'node:fs'
import {dirname, join} from 'node:path'
import {REPO_ROOT} from './lib/load-csv.mjs'
import {buildSearchIndex} from '../lib/site/search.mjs'

const OUT = join(REPO_ROOT, 'data', 'search-index.json')

/*
  AND A SECOND FILE, FOR THE BROWSER.

  public/suggest.json is what the search box's dropdown reads: label, href,
  one meta line, match terms and a coordinate pair, for every published
  city, county and venue. It goes in public/ rather than data/ because it is
  fetched by the visitor, once, the first time they tap the search field.

  It is the same traversal as the index above — same link graph, same
  published set — so the two can never disagree about what exists. See
  buildSuggest() in lib/site/search.mjs for why it is a separate, smaller
  file rather than the same one.
*/
const SUGGEST_OUT = join(REPO_ROOT, 'public', 'suggest.json')

const {entries, zip, venuesTotal, suggest} = buildSearchIndex(REPO_ROOT)

/*
  `haystack` is derived from `terms` on load, so writing both would ship the
  same words twice for no reason.
*/
const slim = entries.map(({haystack, ...e}) => e)

mkdirSync(dirname(OUT), {recursive: true})
writeFileSync(OUT, JSON.stringify({
  note: 'Generated by scripts/build-search-index.mjs. Do not edit by hand.',
  built: new Date().toISOString().slice(0, 10),
  venuesTotal,
  zip,
  entries: slim,
}, null, 1) + '\n', 'utf8')

/*
  No indentation on this one. It is served to visitors rather than read in a
  diff, and pretty-printing it would roughly double a file a phone has to
  download.
*/
const suggestDoc = JSON.stringify({
  note: 'Generated by scripts/build-search-index.mjs. Do not edit by hand.',
  built: new Date().toISOString().slice(0, 10),
  ...suggest,
})
mkdirSync(dirname(SUGGEST_OUT), {recursive: true})
writeFileSync(SUGGEST_OUT, suggestDoc + '\n', 'utf8')

const byType = {}
for (const e of slim) byType[e.type] = (byType[e.type] ?? 0) + 1
const kb = n => `${Math.round(n / 1024)} KB`

console.log('search index written to data/search-index.json')
console.log(`  entries      ${slim.length}  (${Object.entries(byType).map(([k, v]) => `${k} ${v}`).join(', ')})`)
console.log(`  zip codes    ${Object.keys(zip).length}  (only those resolving to a published county)`)
console.log(`  venue total  ${venuesTotal}`)
console.log(`  size         ${kb(JSON.stringify({zip, entries: slim}).length)}`)

console.log('suggest index written to public/suggest.json')
console.log(`  places       ${suggest.places.length}  (cities and counties)`)
console.log(`  courts       ${suggest.courts.length}  (published venues with coordinates)`)
console.log(`  size         ${kb(suggestDoc.length)}  (sent to the browser on first focus)`)
